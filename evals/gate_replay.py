#!/usr/bin/env python3
"""Replay the policy gate (`.github/triage/policy_gate.py`) over every output
the agent proposed in the committed runs (`runs/*/logs/*/safeoutputs.jsonl`),
as if each had passed through the gate before being written.

  python evals/gate_replay.py      # writes evals/golden/gate_replay.md
"""
import glob
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
GOLDEN = os.path.join(HERE, "golden")
os.environ.setdefault("RICH_TRIAGE_TRACE", os.devnull)
sys.path.insert(0, os.path.join(ROOT, ".github", "triage"))

import policy_gate  # noqa: E402


def replayed_issue(case_dir):
    """The issue as the replay files it: owner-authored, with the marker."""
    inp = json.load(open(os.path.join(case_dir, "input.json"), encoding="utf-8"))
    cid = os.path.basename(case_dir)
    marker = (f"<!-- golden-case: {cid} filed: {inp['created_at']}"
              f" as: {inp.get('author_association') or 'NONE'} -->")
    return {"author_association": "OWNER", "body": (inp["body"] or "") + "\n\n" + marker}


def main():
    os.chdir(ROOT)  # check_comment resolves Rich files from the working directory
    cases = {os.path.basename(d): d for sub in ("cases", "adversarial", "heldout")
             for d in glob.glob(os.path.join(GOLDEN, sub, "*"))}
    rows, blocked = [], 0
    for log in sorted(glob.glob(os.path.join(GOLDEN, "runs", "*", "logs", "*", "safeoutputs.jsonl"))):
        run, cid = log.split(os.sep)[-4], log.split(os.sep)[-2]
        if cid not in cases:
            continue
        items = [json.loads(l) for l in open(log, encoding="utf-8") if l.strip()]
        problems = policy_gate.gate(items, replayed_issue(cases[cid]))
        blocked += bool(problems)
        rows.append(f"| {run} | {cid} | {'BLOCK' if problems else 'pass'} | {'; '.join(problems) or '-'} |")
    out = [
        "# Policy gate replayed over committed outputs\n",
        f"{len(rows) - blocked}/{len(rows)} proposed output sets pass; {blocked} would have been "
        "blocked. Generated by `evals/gate_replay.py`.\n",
        "| Run | Case | Gate | Problems |",
        "| --- | --- | --- | --- |",
        *rows,
    ]
    open(os.path.join(GOLDEN, "gate_replay.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
    print(out[1])


if __name__ == "__main__":
    main()
